function mergeBlock(
  block: BlogBlock,
  overlay: BlockOverlay,
  context: string,
): BlogBlock {
  switch (block.type) {
    case "paragraph":
    case "subheading":
      if (overlay.text === undefined) throw new Error(`${context}: missing text`);
      return { ...block, text: overlay.text };
    case "linkedParagraph":
      if (
        overlay.before === undefined ||
        overlay.linkText === undefined ||
        overlay.after === undefined
      ) {
        throw new Error(`${context}: missing linked paragraph text`);
      }
      return {
        ...block,
        before: overlay.before,
        linkText: overlay.linkText,
        after: overlay.after,
      };
    case "orderedList":
    case "unorderedList":
      if (!overlay.items || overlay.items.length !== block.items.length) {
        throw new Error(`${context}: list item count mismatch`);
      }
      return { ...block, items: overlay.items };
    case "contactCta":
      if (overlay.text === undefined) throw new Error(`${context}: missing text`);
      return {
        ...block,
        text: overlay.text,
        whatsappLabel: overlay.whatsappLabel,
      };
    case "visitingInfo":
      return block;
  }
}

function localize(post: BlogPost, overlay: PostOverlay): BlogPost {
  if (
    overlay.sections.length !== post.body.sections.length ||
    overlay.faq.length !== post.faq.length ||
    overlay.relatedLabels.length !== post.relatedLinks.length
  ) {
    throw new Error(`Malayalam overlay does not match article: ${post.slug}`);
  }

  return {
    ...post,
    title: overlay.title,
    metaTitle: overlay.metaTitle,
    description: overlay.description,
    heroImage: { ...post.heroImage, alt: overlay.heroAlt },
    body: {
      hook: overlay.hook,
      introduction: overlay.introduction,
      internationalTerms: overlay.internationalTerms ?? "",
      sections: post.body.sections.map((section, sectionIndex) => {
        const sectionOverlay = overlay.sections[sectionIndex];
        const context = `${post.slug} section ${sectionIndex}`;

        if (sectionOverlay.blocks.length !== section.blocks.length) {
          throw new Error(`${context}: block count mismatch`);
        }

        return {
          ...section,
          heading: sectionOverlay.heading,
          blocks: section.blocks.map((block, blockIndex) =>
            mergeBlock(
              block,
              sectionOverlay.blocks[blockIndex],
              `${context} block ${blockIndex}`,
            ),
          ),
        };
      }),
    },
    faq: overlay.faq,
    relatedLinks: post.relatedLinks.map((link, index) => ({
      ...link,
      label: overlay.relatedLabels[index],
    })),
  };
}

export function getMalayalamPost(slug: string): BlogPost | undefined {
  const post = blogPosts.find((entry) => entry.slug === slug);
  const overlay = overlays[slug];

  return post && overlay ? localize(post, overlay) : undefined;
}

export const malayalamPostSlugs = blogPosts
  .filter((post) => overlays[post.slug])
  .map((post) => post.slug);
